"""Write ideas/v1/_INDEX.md: per-domain counts and bank-wide totals. Run after any bank change."""
import os, sys, json, glob
from collections import Counter
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from intelligence import ideas as I

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows, tot = [], Counter()
allb = []
for p in sorted(glob.glob(os.path.join(ROOT, "ideas", "v1", "*.json"))):
    name = os.path.basename(p)[:-5]
    if name.startswith("_"): continue
    b = json.load(open(p, encoding="utf-8")); allb += b
    prim = Counter(it["bottleneck"][0] for it in b)
    top = ", ".join(f"{k} {v}" for k, v in prim.most_common(3))
    cards = {c for it in b for c in it["sources"]["cards"]}
    gp = sum(1 for it in b if it["general_practice"])
    rows.append((name, len(b), gp, len(cards), top))
    tot["ideas"] += len(b); tot["gp"] += gp
s = I.summary(allb)
basis = Counter(it["expected_effect"]["basis"] for it in allb)
conf = Counter(it["confidence"] for it in allb)
eff = Counter(it["effort"]["size"] for it in allb)
out = ["# Idea bank index", "", f"Generated by `scripts/idea_index.py`. {s['ideas']} ideas across {s['domains']} domains; {tot['gp']} tagged general practice (no library source).", "",
       "| Domain | Ideas | General practice | Cards cited | Top primary bottlenecks |", "|---|---|---|---|---|"]
out += [f"| {n} | {c} | {g} | {k} | {t} |" for n, c, g, k, t in rows]
out += ["", "## Bank-wide", "", "| Primary bottleneck | Ideas |", "|---|---|"]
out += [f"| {k} | {v} |" for k, v in sorted(s["by_primary_bottleneck"].items(), key=lambda x: -x[1])]
out += ["", f"Evidence basis: {dict(basis)}. Confidence: {dict(conf)}. Effort: {dict(eff)}.", "",
        "Query: `python3 scripts/ideas.py --bottleneck conversion --store hero_sku india_mobile --top 20`. Duplicates: `python3 scripts/idea_dupes.py`."]
open(os.path.join(ROOT, "ideas", "v1", "_INDEX.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out[:4] + out[-6:]))
