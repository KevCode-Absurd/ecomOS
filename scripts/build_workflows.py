"""Merge wave 4 workflows and skill trees; write SKILL.md files, indexes and the workflows page.

Inputs:  agents/specialists/*.workflows.json, agents/specialists/*.skills.json, agents/loop/LOOP.workflows.json, agents/catalogue.json, agents/id_aliases.json
Outputs: agents/workflows/workflows.json, agents/WORKFLOWS.md, agents/skills/<agent>/<path>/SKILL.md, agents/SKILL-TREE.md, reviews/workflows/ecomos-workflows.html
Usage:   python3 scripts/build_workflows.py
"""
import collections, glob, html, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "agents")
ORDER = ["ORCH", "DIAG", "PROP", "REG", "QA", "BRN", "SCT", "SITE", "CREA", "MEDIA", "LIFE", "ORG", "PROD", "MONEY", "BRAND"]
NAMES = {"ORCH": "Orchestrator", "DIAG": "Diagnose", "PROP": "Propose", "REG": "Registrar", "QA": "QA Gate", "BRN": "Brand Brain Keeper", "SCT": "Reference Scout",
         "SITE": "Site", "CREA": "Paid creative and copy", "MEDIA": "Media buyer", "LIFE": "Lifecycle", "ORG": "Organic and search", "PROD": "Product and supply", "MONEY": "Money and ops", "BRAND": "Brand strategist"}
E = lambda s: html.escape(str(s if s is not None else ""))


def load():
    alias = json.load(open(os.path.join(A, "id_aliases.json"))) if os.path.exists(os.path.join(A, "id_aliases.json")) else {}
    caps = {c["id"]: c for c in json.load(open(os.path.join(A, "catalogue.json"), encoding="utf-8"))}
    wfs, skills = [], []
    files = sorted(glob.glob(os.path.join(A, "specialists", "*.workflows.json"))) + [os.path.join(A, "loop", "LOOP.workflows.json")]
    for f in files:
        if not os.path.exists(f):
            continue
        code = os.path.basename(f).split(".")[0]
        for w in json.load(open(f, encoding="utf-8")):
            w["agent"] = w.get("agent") or code
            w["capabilities"] = [alias.get(re.sub(r"-C(\d)$", r"-C0\1", c), re.sub(r"-C(\d)$", r"-C0\1", c)) for c in w.get("capabilities", [])]
            w["unknown_capabilities"] = [c for c in w["capabilities"] if c not in caps]
            wfs.append(w)
    for f in sorted(glob.glob(os.path.join(A, "specialists", "*.skills.json"))):
        code = os.path.basename(f).split(".")[0]
        for s in json.load(open(f, encoding="utf-8")):
            s["agent"] = code
            skills.append(s)
    wfs.sort(key=lambda w: (ORDER.index(w["agent"]) if w["agent"] in ORDER else 99, w["id"]))
    return wfs, skills, caps


def write_skill_files(skills):
    n = 0
    for s in skills:
        path = re.sub(r"[^a-z0-9/_-]+", "-", (s.get("id") or "").lower()).strip("/-")
        if not path or not s.get("skill_md"):
            continue
        d = os.path.join(A, "skills", *path.split("/"))
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "SKILL.md"), "w", encoding="utf-8").write(s["skill_md"].strip() + "\n")
        n += 1
    return n


def render_workflows_md(wfs):
    L = ["# ecomOS workflows", "", f"{len(wfs)} predetermined workflows. Each is how a good person in the role would do the job, step by step, with inputs, the skill each step uses, the output and the check before the next step. Generated by `scripts/build_workflows.py`.", ""]
    by = collections.defaultdict(list)
    for w in wfs:
        by[w["agent"]].append(w)
    for ag in ORDER:
        if ag not in by:
            continue
        L.append(f"## {NAMES[ag]} ({ag}), {len(by[ag])} workflows\n")
        for w in by[ag]:
            L.append(f"### {w['id']} {w['name']}\n")
            L.append(f"Trigger: {w.get('trigger')}. Human role: {w.get('human_role')}. Capabilities: {', '.join(w.get('capabilities', []))}. Needs: {', '.join(w.get('inputs_required', []))}.\n")
            for st in w.get("steps", []):
                L.append(f"{st.get('n')}. **{st.get('name')}.** {st.get('does')} Skill: `{st.get('skill') or 'none'}`. Output: {st.get('output')}. Check: {st.get('check')}." + (f" Ask the founder if: {st.get('ask_founder_if')}." if st.get('ask_founder_if') else ""))
            L.append(f"\nOutputs: {', '.join(w.get('outputs', []))}. QA: {'; '.join(w.get('qa', []))}. Read point: {w.get('read_point')}. Duration: {w.get('typical_duration')}.\n")
    return "\n".join(L)


def render_tree_md(skills):
    L = ["# ecomOS skill tree", "", f"{len(skills)} skills including sub-skills, each with a SKILL.md under `agents/skills/`. The shared skills every agent may call are in `agents/skills/<name>/`. An agent picks a sub-skill by its `select_by` switches. Generated by `scripts/build_workflows.py`.", ""]
    by = collections.defaultdict(list)
    for s in skills:
        by[s["agent"]].append(s)
    for ag in ORDER:
        if ag not in by:
            continue
        L.append(f"## {NAMES[ag]} ({ag}), {len(by[ag])} skills\n")
        roots = [s for s in by[ag] if not s.get("parent")]
        kids = collections.defaultdict(list)
        for s in by[ag]:
            if s.get("parent"):
                kids[s["parent"]].append(s)
        def emit(s, depth):
            sel = ", ".join(f"{k}={v}" for k, v in (s.get("select_by") or {}).items())
            L.append(f"{'  ' * depth}- `{s['id']}` {s.get('name')}. Invoke when: {s.get('invoke_when')}." + (f" Select by: {sel}." if sel else "") + (f" Shared with: {', '.join(s['shared_with'])}." if s.get("shared_with") else ""))
            for k in kids.get(s["id"], []):
                emit(k, depth + 1)
        for r in roots:
            emit(r, 0)
        L.append("")
    return "\n".join(L)


def render_page(wfs, skills, caps):
    sk = {s["id"]: s for s in skills}
    kids = collections.defaultdict(list)
    for s in skills:
        if s.get("parent"):
            kids[s["parent"]].append(s)
    def wf_html(w):
        steps = "".join(f"<li><div class='sn'>{E(st.get('n'))}</div><div class='sb'><b>{E(st.get('name'))}</b><p>{E(st.get('does'))}</p><div class='meta'>{('<span class=skill>' + E(st.get('skill')) + '</span>') if st.get('skill') else '<span class=grey>no skill, judgement</span>'}{''.join('<span class=tool>' + E(t) + '</span>' for t in (st.get('tools') or []))}</div><div class='io'><span><b>Out</b> {E(st.get('output'))}</span><span><b>Check</b> {E(st.get('check'))}</span>{('<span class=ask><b>Ask founder if</b> ' + E(st.get('ask_founder_if')) + '</span>') if st.get('ask_founder_if') else ''}</div></div></li>" for st in w.get("steps", []))
        return f"<details class='wf' id='wf-{E(w['id'])}'><summary><span class='id'>{E(w['id'])}</span><b>{E(w['name'])}</b><span class='muted'>{E(w.get('trigger'))} · {len(w.get('steps', []))} steps</span></summary><div class='wb'><p class='muted'>As a person would call it: {E(w.get('human_role'))}. Needs: {E(', '.join(w.get('inputs_required', [])))}. Capabilities: {E(', '.join(w.get('capabilities', [])))}.</p><ol class='steps'>{steps}</ol><p class='muted small'>Outputs: {E(', '.join(w.get('outputs', [])))}. QA before the gate: {E('; '.join(w.get('qa', [])))}. Read point: {E(w.get('read_point'))}. Duration: {E(w.get('typical_duration'))}.</p></div></details>"
    def skill_html(s, depth=0):
        sel = ", ".join(f"{k}={v}" for k, v in (s.get("select_by") or {}).items())
        inner = "".join(skill_html(k, depth + 1) for k in kids.get(s["id"], []))
        return f"<details class='sk d{depth}'><summary><code>{E(s['id'])}</code> <b>{E(s.get('name'))}</b>{(' <span class=sel>' + E(sel) + '</span>') if sel else ''}</summary><div class='skb'><p><b>Invoke when</b> {E(s.get('invoke_when'))}</p><p><b>Needs</b> {E(', '.join(s.get('inputs_required', []) or []))}</p><p><b>Output</b> {E(s.get('output'))}</p><p class='muted small'>Used by {E(', '.join(s.get('used_by', []) or []))}{(' · shared with ' + E(', '.join(s.get('shared_with')))) if s.get('shared_with') else ''}</p><details><summary>SKILL.md</summary><pre>{E(s.get('skill_md'))}</pre></details></div>{inner}</details>"
    byw = collections.defaultdict(list); bys = collections.defaultdict(list)
    for w in wfs:
        byw[w["agent"]].append(w)
    for s in skills:
        bys[s["agent"]].append(s)
    wf_sections = "".join(f"<section class='grp' id='wf-{ag}'><h2>{E(NAMES[ag])} <small>{ag} · {len(byw[ag])} workflows</small></h2>{''.join(wf_html(w) for w in byw[ag])}</section>" for ag in ORDER if ag in byw)
    sk_sections = "".join(f"<section class='grp' id='sk-{ag}'><h2>{E(NAMES[ag])} <small>{ag} · {len(bys[ag])} skills</small></h2>{''.join(skill_html(s) for s in bys[ag] if not s.get('parent'))}</section>" for ag in ORDER if ag in bys)
    # the end-to-end example: the first CREA workflow, or the first workflow overall
    ex = next((w for w in wfs if w["agent"] == "CREA"), wfs[0] if wfs else None)
    ex_html = ""
    if ex:
        rows = ""
        for st in ex.get("steps", []):
            s = sk.get(st.get("skill") or "")
            rows += f"<div class='exrow'><div class='exn'>{E(st.get('n'))}</div><div class='exs'><b>{E(st.get('name'))}</b><p>{E(st.get('does'))}</p><div class='io'><span><b>Out</b> {E(st.get('output'))}</span><span><b>Check</b> {E(st.get('check'))}</span></div></div><div class='exk'>{('<div class=lit><code>' + E(st.get('skill')) + '</code>' + (('<p>' + E(s.get('invoke_when')) + '</p>') if s else '') + '</div>') if st.get('skill') else '<div class=dim>judgement step, no skill</div>'}{''.join('<span class=tool>' + E(t) + '</span>' for t in (st.get('tools') or []))}</div></div>"
        ex_html = f"<div class='ex'><div class='exhead'><span class='eyebrow'>{E(NAMES.get(ex['agent'], ex['agent']))} · {E(ex['id'])}</span><h2>{E(ex['name'])}</h2><p class='muted'>Read it as a new hire's first week: each step says what they do, what comes out, what they check, and which skill they pull off the shelf. Skills light up on the right.</p></div>{rows}</div>"
    stats = {"workflows": len(wfs), "steps": sum(len(w.get("steps", [])) for w in wfs), "skills": len(skills), "subskills": sum(1 for s in skills if s.get("parent")), "agents": len(byw)}
    tpl = open(os.path.join(ROOT, "scripts", "workflows_page.html"), encoding="utf-8").read()
    routing = open(os.path.join(A, "ROUTING.md"), encoding="utf-8").read() if os.path.exists(os.path.join(A, "ROUTING.md")) else ""
    return tpl.replace("<!--EXAMPLE-->", ex_html).replace("<!--WORKFLOWS-->", wf_sections).replace("<!--SKILLS-->", sk_sections).replace("/*STATS*/", json.dumps(stats)).replace("<!--ROUTING-->", md_tables(routing))


def md_tables(md):
    """Minimal markdown to HTML for ROUTING.md: headings, paragraphs, tables."""
    out = []; lines = md.splitlines(); i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith("#"):
            n = len(l) - len(l.lstrip("#")); out.append(f"<h{min(n + 1, 4)}>{E(l.lstrip('#').strip())}</h{min(n + 1, 4)}>"); i += 1
        elif l.strip().startswith("|"):
            rows = []
            while i < len(lines) and lines[i].strip().startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")]); i += 1
            rows = [r for r in rows if not all(re.match(r"^:?-+:?$", c) for c in r)]
            out.append("<div class='tw'><table><tr>" + "".join(f"<th>{E(c)}</th>" for c in rows[0]) + "</tr>" + "".join("<tr>" + "".join(f"<td>{E(c).replace('`', '')}</td>" for c in r) + "</tr>" for r in rows[1:]) + "</table></div>")
        elif l.strip() == "":
            i += 1
        else:
            buf = []
            while i < len(lines) and lines[i].strip() and not lines[i].startswith("#") and not lines[i].strip().startswith("|"):
                buf.append(lines[i]); i += 1
            out.append(f"<p>{E(' '.join(buf)).replace('`', '')}</p>")
    return "\n".join(out)


if __name__ == "__main__":
    wfs, skills, caps = load()
    os.makedirs(os.path.join(A, "workflows"), exist_ok=True)
    json.dump(wfs, open(os.path.join(A, "workflows", "workflows.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    json.dump(skills, open(os.path.join(A, "workflows", "skills.json"), "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    open(os.path.join(A, "WORKFLOWS.md"), "w", encoding="utf-8").write(render_workflows_md(wfs))
    open(os.path.join(A, "SKILL-TREE.md"), "w", encoding="utf-8").write(render_tree_md(skills))
    n = write_skill_files(skills)
    os.makedirs(os.path.join(ROOT, "reviews", "workflows"), exist_ok=True)
    out = os.path.join(ROOT, "reviews", "workflows", "ecomos-workflows.html")
    open(out, "w", encoding="utf-8").write(render_page(wfs, skills, caps))
    covered = set(c for w in wfs for c in w["capabilities"])
