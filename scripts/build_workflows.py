    print(len(wfs), "workflows;", len(skills), "skills;", n, "SKILL.md files;", out, os.path.getsize(out) // 1024, "KB; specialist capabilities covered", len([c for c in spec if c in covered]), "of", len(spec), "; unknown ids", unk)
